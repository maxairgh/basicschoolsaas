    public function run(): void
    {
        $now = now();

        DB::table('regions')->upsert(
            array_map(fn (array $region) => [
                'id' => $region[0],
                'region_name' => $region[1],
                'region_capital' => $region[2],
                'created_at' => $now,
                'updated_at' => $now,
            ], self::REGIONS),
            ['id'],
            ['region_name', 'region_capital', 'updated_at'],
        );

        DB::table('districts')->upsert(
            array_map(fn (array $district) => [
                'id' => $district[0],
                'region_id' => $district[1],
                'district_name' => $district[2],
                'district_capital' => $district[3],
                'district_category' => $district[4],
                'created_at' => $now,
                'updated_at' => $now,
            ], self::DISTRICTS),
            ['id'],
            ['region_id', 'district_name', 'district_capital', 'district_category', 'updated_at'],
        );
    }
